#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
MMADA_ROOT="$(cd "${ROOT}/../.." && pwd)"
PYTHON="${PYTHON:-/root/miniconda3/bin/python}"
DATASET="${DATASET:-M3CoT_COT}"
MODEL="${MODEL:-MMaDA-MixCoT-History-VCHD-H2-CCAWv2}"
RUN_ID="${MMADA_RUN_ID:-m3cot_history_vchd_h2_ccawv2_$(date +%Y%m%d_%H%M%S)}"
WORK_DIR="${WORK_DIR:-${ROOT}/outputs/${RUN_ID}}"
LOG_FILE="${LOG_FILE:-${ROOT}/${RUN_ID}.log}"

cd "${ROOT}"
export PYTHONPATH="${MMADA_ROOT}:${ROOT}:${PYTHONPATH:-}"
export LMUData="${LMUData:-${ROOT}/LMUData}"
export MMADA_MODEL_PATH="${MMADA_MODEL_PATH:-/root/autodl-tmp/MMaDA-8B-MixCoT}"
export MMADA_TOKENIZER_PATH="${MMADA_TOKENIZER_PATH:-${MMADA_MODEL_PATH}}"
export MMADA_VQ_MODEL_PATH="${MMADA_VQ_MODEL_PATH:-/root/autodl-tmp/magvitv2}"
export MMADA_DECODE_STRATEGY=vchd
export MMADA_VCHD_ALPHA="${MMADA_VCHD_ALPHA:-0.25}"
export MMADA_VCHD_BETA="${MMADA_VCHD_BETA:-0.1}"
export MMADA_VCHD_TAU_BASE="${MMADA_VCHD_TAU_BASE:-0.10}"
export MMADA_VCHD_TAU_CONTRAST="${MMADA_VCHD_TAU_CONTRAST:-0.90}"
export MMADA_VCHD_MASK_CAPACITY="${MMADA_VCHD_MASK_CAPACITY:-16}"
export MMADA_VCHD_MAX_COMMIT="${MMADA_VCHD_MAX_COMMIT:-16}"
export MMADA_VCHD_MAX_PHYSICAL_SPAN="${MMADA_VCHD_MAX_PHYSICAL_SPAN:-128}"
export MMADA_VCHD_FORCE_MATH_SDPA="${MMADA_VCHD_FORCE_MATH_SDPA:-1}"
export MMADA_VCHD_FALLBACK_TO_RAW="${MMADA_VCHD_FALLBACK_TO_RAW:-0}"
export MMADA_VCHD_FALLBACK_CAPACITY="${MMADA_VCHD_FALLBACK_CAPACITY:-0}"
export MMADA_VCHD_FALLBACK_POLICY="${MMADA_VCHD_FALLBACK_POLICY:-readiness}"
export MMADA_VCHD_CACHE_TYPE="${MMADA_VCHD_CACHE_TYPE:-none}"
export MMADA_VCHD_HISTORY="${MMADA_VCHD_HISTORY:-1}"
export MMADA_VCHD_HISTORY_TOP_V="${MMADA_VCHD_HISTORY_TOP_V:-8}"
export MMADA_VCHD_HISTORY_EMA_DECAY="${MMADA_VCHD_HISTORY_EMA_DECAY:-0.7}"
export MMADA_VCHD_HISTORY_PENALTY_SCALE="${MMADA_VCHD_HISTORY_PENALTY_SCALE:-4.0}"
export MMADA_VCHD_HISTORY_ANCHOR_MIN_CONSISTENT="${MMADA_VCHD_HISTORY_ANCHOR_MIN_CONSISTENT:-2}"
export MMADA_VCHD_CCAW="${MMADA_VCHD_CCAW:-1}"
export MMADA_VCHD_CCAW_MODE="${MMADA_VCHD_CCAW_MODE:-inverse_window}"
export MMADA_VCHD_CCAW_BLOCK_SIZE="${MMADA_VCHD_CCAW_BLOCK_SIZE:-32}"
export MMADA_VCHD_CCAW_MIN_COMMIT="${MMADA_VCHD_CCAW_MIN_COMMIT:-1}"
export MMADA_VCHD_CCAW_QUALIFIED_BUDGET="${MMADA_VCHD_CCAW_QUALIFIED_BUDGET:-1}"
export MMADA_VCHD_CCAW_MAX_CAPACITY="${MMADA_VCHD_CCAW_MAX_CAPACITY:-64}"
export MMADA_VCHD_CCAW_PRESSURE_DECAY="${MMADA_VCHD_CCAW_PRESSURE_DECAY:-0.8}"
export MMADA_VCHD_CCAW_PRESSURE_SCALE="${MMADA_VCHD_CCAW_PRESSURE_SCALE:-1.0}"
export MMADA_VCHD_CCAW_EXPAND_STEP="${MMADA_VCHD_CCAW_EXPAND_STEP:-4}"
export MMADA_VCHD_CCAW_SHRINK_STEP="${MMADA_VCHD_CCAW_SHRINK_STEP:-8}"
export MMADA_VCHD_COLLECT_TRACE="${MMADA_VCHD_COLLECT_TRACE:-0}"
export MMADA_VCHD_RETURN_REPORT="${MMADA_VCHD_RETURN_REPORT:-0}"
if [[ "${MMADA_VCHD_RETURN_REPORT}" == "1" ]]; then
  export MMADA_VCHD_REPORT_DIR="${MMADA_VCHD_REPORT_DIR:-${WORK_DIR}/reports}"
fi
export MMADA_RUN_ID="${RUN_ID}"
export MMADA_SKIP_LOCALIZE=1
export MMADA_COLLECT_ATTENTION=0
export PYTORCH_CUDA_ALLOC_CONF="${PYTORCH_CUDA_ALLOC_CONF:-expandable_segments:True}"
export HF_HUB_OFFLINE="${HF_HUB_OFFLINE:-1}"
export TRANSFORMERS_OFFLINE="${TRANSFORMERS_OFFLINE:-1}"
export CUDA_VISIBLE_DEVICES="${CUDA_VISIBLE_DEVICES:-0}"
export PYTHONUNBUFFERED=1

# MMADA_SAMPLE_N is a runner convenience knob; VLMEvalKit consumes explicit
# MMADA_INDICES/MMADA_INDEX_FILE instead.
if [[ -n "${MMADA_SAMPLE_N:-}" \
      && -z "${MMADA_INDICES:-}" \
      && -z "${MMADA_INDEX_FILE:-}" ]]; then
  if (( MMADA_SAMPLE_N < 1 )); then
    echo "MMADA_SAMPLE_N must be at least 1" >&2
    exit 2
  fi
  MMADA_INDICES="$(seq -s, 0 "$((MMADA_SAMPLE_N - 1))")"
  export MMADA_INDICES
fi

mkdir -p "${WORK_DIR}"
echo "[History-VCHD] model=${MODEL} dataset=${DATASET} run_id=${RUN_ID}"
echo "[History-VCHD] output=${WORK_DIR} log=${LOG_FILE}"
exec "${PYTHON}" run.py \
  --data "${DATASET}" \
  --model "${MODEL}" \
  --work-dir "${WORK_DIR}" \
  --mode all \
  >"${LOG_FILE}" 2>&1
