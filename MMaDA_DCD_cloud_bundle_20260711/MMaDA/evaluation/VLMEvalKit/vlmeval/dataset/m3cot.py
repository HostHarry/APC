"""M3CoT dataset adapter and official-rule local evaluator."""

from __future__ import annotations

import json
import os
import os.path as osp
import re
import string

import pandas as pd

from .image_mcq import ImageMCQDataset
from ..smp import LMUDataRoot, dump, load, toliststr


ANSWER_LABELS = list(string.ascii_uppercase)


def extract_m3cot_answer(text: str, choices: list[str]) -> str:
    """Extract an option using M3CoT's official ``judge_answer`` rules."""
    text = str(text)
    if '[Answer]' in text:
        text = (
            text.split('[Answer]')[-1]
            .split('[Rationale]')[0]
            .split('[Context]')[0]
        )

    matches = re.findall(r'\(([A-Za-z])\)', text)
    if matches:
        return matches[-1].upper()

    matched_labels = []
    for index, choice in enumerate(choices):
        if str(choice).lower() in text.lower():
            matched_labels.append(ANSWER_LABELS[index])
    if matched_labels:
        return matched_labels[-1]

    normalized = re.sub(r'[\n.,!?]', ' ', text)
    tokens = normalized.split(' ')
    for index in range(len(choices)):
        if ANSWER_LABELS[index] in tokens:
            matched_labels.append(ANSWER_LABELS[index])
    if matched_labels:
        return matched_labels[-1]

    for index in range(len(choices)):
        if ANSWER_LABELS[index].lower() in tokens:
            matched_labels.append(ANSWER_LABELS[index])
    return matched_labels[-1] if matched_labels else 'FAILED'


class M3CoTDataset(ImageMCQDataset):
    """Official M3CoT test split with Direct and CoT prompt variants.

    ``M3CoT`` is an alias for ``M3CoT_COT``. All variants read the common
    ``$LMUData/M3CoT.tsv`` generated by ``scripts/build_m3cot_tsv.py``.
    """

    TYPE = 'MCQ'
    DATASET_URL = {
        'M3CoT': '',
        'M3CoT_COT': '',
        'M3CoT_DIRECT': '',
    }
    DATASET_MD5 = {}

    def load_data(self, dataset):
        data_path = osp.join(LMUDataRoot(), 'M3CoT.tsv')
        self.data_path = data_path
        if not osp.isfile(data_path):
            raise FileNotFoundError(
                f'Missing {data_path}. Run scripts/build_m3cot_tsv.py first.')
        data = load(data_path)
        required = {
            'index', 'id', 'image_path', 'question', 'answer',
            'domain', 'topic', 'category',
        }
        missing = required - set(data.columns)
        if missing:
            raise ValueError(
                f'M3CoT.tsv is missing columns: {sorted(missing)}')
        return data

    @property
    def prompt_mode(self) -> str:
        return (
            'direct'
            if self.dataset_name == 'M3CoT_DIRECT'
            else 'cot'
        )

    def build_prompt(self, line):
        if isinstance(line, int):
            line = self.data.iloc[line]

        if self.meta_only:
            target_path = toliststr(line['image_path'])
        else:
            target_path = self.dump_image(line)

        choices = {
            label: str(line[label])
            for label in ANSWER_LABELS
            if label in line and not pd.isna(line[label])
        }
        if not choices:
            raise ValueError(f'M3CoT sample {line["id"]} has no choices.')

        sections = []
        context = line.get('context', '')
        if not pd.isna(context) and str(context).strip():
            sections.append(f'[Context]\n{str(context).strip()}')
        sections.append(f'[Question]\n{str(line["question"]).strip()}')
        option_text = '\n'.join(
            f'({label}) {choice}' for label, choice in choices.items())
        sections.append(f'[Choices]\n{option_text}')
        prompt = '\n'.join(sections)

        if self.prompt_mode == 'cot':
            prompt += (
                "\n\nLet's think step-by-step! End your response with the "
                'final option in parentheses, for example (A).'
            )
        else:
            prompt += (
                '\n\nSelect the correct answer and respond only with its '
                'option in parentheses, for example (A).'
            )

        messages = []
        if isinstance(target_path, list):
            messages.extend(
                dict(type='image', value=path) for path in target_path)
        else:
            messages.append(dict(type='image', value=target_path))
        messages.append(dict(type='text', value=prompt))
        return messages

    def evaluate(self, eval_file, **judge_kwargs):
        del judge_kwargs  # M3CoT uses deterministic local matching, no API.
        data = load(eval_file)
        required = {
            'id', 'question', 'prediction', 'answer', 'domain', 'topic',
        }
        missing = required - set(data.columns)
        if missing:
            raise ValueError(
                f'M3CoT prediction file is missing: {sorted(missing)}')

        details = []
        official_records = []
        for _, row in data.iterrows():
            choices = [
                str(row[label])
                for label in ANSWER_LABELS
                if label in row and not pd.isna(row[label])
            ]
            prediction = str(row['prediction'])
            predicted_option = extract_m3cot_answer(prediction, choices)
            answer = str(row['answer']).strip().upper()
            hit = int(predicted_option == answer)

            detail = dict(row)
            detail.update(pred_option=predicted_option, hit=hit)
            details.append(detail)
            official_records.append({
                'id': str(row['id']),
                'choices': choices,
                'answer': answer,
                'domain': str(row['domain']),
                'topic': str(row['topic']),
                'messages': [str(row['question']), prediction],
            })

        details_df = pd.DataFrame(details)
        suffix = osp.splitext(eval_file)[1]
        stem = eval_file[:-len(suffix)] if suffix else eval_file
        detail_file = f'{stem}_m3cot_details.xlsx'
        dump(details_df, detail_file)

        score_rows = []

        def append_score(level, frame, domain='', topic=''):
            total = len(frame)
            correct = int(frame['hit'].sum())
            score_rows.append({
                'level': level,
                'domain': domain,
                'topic': topic,
                'total': total,
                'correct': correct,
                'accuracy': correct / total if total else 0.0,
                'accuracy_percent': (
                    correct / total * 100.0 if total else 0.0),
            })

        append_score('overall', details_df)
        for domain in sorted(details_df['domain'].unique()):
            domain_df = details_df[details_df['domain'] == domain]
            append_score('domain', domain_df, domain=domain)
            for topic in sorted(domain_df['topic'].unique()):
                topic_df = domain_df[domain_df['topic'] == topic]
                append_score(
                    'topic', topic_df, domain=domain, topic=topic)

        score_df = pd.DataFrame(score_rows)
        score_file = f'{stem}_m3cot_score.csv'
        dump(score_df, score_file)

        summary = {
            'total': {
                'acc': score_rows[0]['accuracy'],
                'total': score_rows[0]['total'],
                'correct': score_rows[0]['correct'],
            },
            'domain': {},
            'topic': {},
        }
        for score in score_rows[1:]:
            value = {
                'acc': score['accuracy'],
                'total': score['total'],
                'correct': score['correct'],
            }
            if score['level'] == 'domain':
                summary['domain'][score['domain']] = value
            else:
                summary['topic'].setdefault(score['domain'], {})[
                    score['topic']
                ] = value
        with open(f'{stem}_m3cot_score.json', 'w', encoding='utf-8') as file:
            json.dump(summary, file, ensure_ascii=False, indent=2)
        with open(
            f'{stem}_m3cot_official.jsonl', 'w', encoding='utf-8'
        ) as file:
            for record in official_records:
                file.write(json.dumps(record, ensure_ascii=False) + '\n')

        print(
            f'[M3CoT] accuracy={score_rows[0]["accuracy_percent"]:.2f}% '
            f'({score_rows[0]["correct"]}/{score_rows[0]["total"]})')
        print(f'[M3CoT] wrote {score_file}')
        return score_df


__all__ = ['M3CoTDataset', 'extract_m3cot_answer']
